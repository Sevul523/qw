    fun getExtendedWordKnowledgeList(): List<WordKnowledge> {
        return RAW_LIST.distinctBy { it.word.trim() }.map { raw ->
            val (simplePos, conj) = ClassicalPosNormalizer.splitPosAndConjugation(raw.pos)
            val defs = raw.meaning.split("/").map { m ->
                Definition(pos = simplePos, meaning = m.trim())
            }
            val extraNotePrefix = when {
                raw.pos.contains("/") && conj.isBlank() -> "品詞用法: ${raw.pos.replace("/", "・")}"
                simplePos == "その他" && raw.pos != "その他" -> "品詞: ${raw.pos}"
                else -> ""
            }
            val baseNote = if (extraNotePrefix.isNotBlank() && !raw.note.contains(extraNotePrefix)) {
                "$extraNotePrefix / ${raw.note}"
            } else {
                raw.note
            }
            val mergedNote = ClassicalPosNormalizer.mergeConjugationIntoNote(
                conjugations = if (conj.isNotBlank()) listOf(conj) else emptyList(),
                existingNote = baseNote
            )
            WordKnowledge(
                word = raw.word,
                definitions = defs,
                deck = raw.deck,
                etymology = raw.note,
                collocations = emptyList(),
                synonyms = emptyList(),
                antonyms = emptyList(),
                note = mergedNote,
                conjugation = conj
            )
        }
    }
